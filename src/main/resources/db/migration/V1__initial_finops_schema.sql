CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL
);

CREATE TABLE uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL,
    owner_id BIGINT NOT NULL,
    CONSTRAINT fk_upload_owner FOREIGN KEY (owner_id) REFERENCES app_users(id)
);

CREATE TABLE resource_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id BIGINT NOT NULL,
    service_name VARCHAR(255) NOT NULL,
    monthly_cost DECIMAL(12,2) NOT NULL,
    cpu_usage DECIMAL(5,2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT fk_resource_upload FOREIGN KEY (upload_id) REFERENCES uploads(id)
);

CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL UNIQUE,
    recommendation VARCHAR(255) NOT NULL,
    estimated_savings DECIMAL(12,2) NOT NULL,
    state VARCHAR(20) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_recommendation_resource FOREIGN KEY (resource_id) REFERENCES resource_usage(id)
);

CREATE TABLE simulations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_name VARCHAR(255) NOT NULL,
    current_cost DECIMAL(12,2) NOT NULL,
    projected_cost DECIMAL(12,2) NOT NULL,
    savings DECIMAL(12,2) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    owner_id BIGINT NOT NULL,
    CONSTRAINT fk_simulation_owner FOREIGN KEY (owner_id) REFERENCES app_users(id)
);

CREATE TABLE budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    service_name VARCHAR(120) NOT NULL,
    monthly_limit DECIMAL(12,2) NOT NULL,
    alert_threshold INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_budget_owner FOREIGN KEY (owner_id) REFERENCES app_users(id)
);

CREATE INDEX idx_upload_owner_uploaded ON uploads(owner_id, uploaded_at);
CREATE INDEX idx_resource_upload ON resource_usage(upload_id);
CREATE INDEX idx_simulation_owner_created ON simulations(owner_id, created_at);
